import Foundation
import TOMLKit
import XCTest
import PaletteCore

/// Per-format syntax invariants for the generated theme files. The native
/// validators (kitty's parser, `zellij setup --check`, `nvim -c luafile`,
/// `fish -n`, `starship prompt`, `btop --debug`, `xmllint`, `plutil`,
/// `git config --list`) are not on CI, so these assert the rules those tools
/// enforce: comment syntax, XML well-formedness, TOML parsing and known keys.
final class ThemeFormatTests: XCTestCase {
    private let palette = PalettePalette(theme: .defaultDark)
    private let metadata = PaletteMetadata(
        source: "theme",
        theme: "Default Dark",
        appearance: "dark",
        themeID: "default-dark",
        generatedAt: Date(timeIntervalSince1970: 1_700_000_000)
    )

    private func render(_ target: ThemingTarget) throws -> String {
        try XCTUnwrap(
            ThemingRenderer.contents(for: target, palette: palette, metadata: metadata),
            "\(target) rendered nothing"
        )
    }

    private func bodyLines(_ text: String) -> [String] {
        text.components(separatedBy: "\n").filter { !$0.isEmpty && !$0.hasPrefix("#") }
    }

    /// First capture of every line matching `pattern`, plus the line itself.
    private func captures(_ pattern: String, in text: String) -> [[String]] {
        guard let regex = try? NSRegularExpression(pattern: pattern) else { return [] }
        return text.components(separatedBy: "\n").compactMap { line in
            let range = NSRange(line.startIndex..<line.endIndex, in: line)
            guard let match = regex.firstMatch(in: line, range: range) else { return nil }
            return (0..<match.numberOfRanges).map { index in
                guard let value = Range(match.range(at: index), in: line) else { return "" }
                return String(line[value])
            }
        }
    }

    // MARK: - Headers

    func testHeaderUsesEachTargetsCommentSyntax() throws {
        for target in ThemingTarget.allCases where target.isImplemented && !target.isBrowser && target != .starship {
            let text = try render(target)
            switch target {
            case .zellij:
                XCTAssertTrue(text.hasPrefix("// generated by Palette"), "\(target)")
                XCTAssertFalse(text.contains("\n# generated"), "\(target) is KDL")
            case .nvim:
                XCTAssertTrue(text.hasPrefix("-- generated by Palette"), "\(target)")
                XCTAssertFalse(text.contains("\n# generated"), "\(target) is Lua")
            case .bat:
                XCTAssertTrue(text.hasPrefix("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"), "\(target)")
                XCTAssertTrue(text.contains("<!-- generated by Palette"), "\(target)")
            default:
                XCTAssertTrue(text.hasPrefix("# generated by Palette"), "\(target)")
            }
        }
    }

    // MARK: - kitty

    func testKittyConfUsesKittyOptions() throws {
        let lines = bodyLines(try render(.kitty))
        let pattern = #"^([a-z_0-9]+)\s+(#[0-9a-f]{6})$"#
        var keys = Set<String>()
        for line in lines {
            let match = captures(pattern, in: line)
            XCTAssertEqual(match.count, 1, "kitty line does not parse: \(line)")
            keys.insert(match.first?[1] ?? "")
        }
        let expected = Set([
            "background", "foreground", "cursor", "cursor_text_color",
            "selection_background", "selection_foreground",
        ] + (0..<16).map { "color\($0)" })
        XCTAssertEqual(keys, expected)
        XCTAssertEqual(lines.count, 22)
    }

    // MARK: - Ghostty

    func testGhosttyConfUsesGhosttyOptions() throws {
        let lines = bodyLines(try render(.ghostty))
        let pattern = #"^([a-z-]+) = (.+)$"#
        var keys = Set<String>()
        var paletteIndices: [Int] = []
        for line in lines {
            let match = captures(pattern, in: line)
            XCTAssertEqual(match.count, 1, "Ghostty line does not parse: \(line)")
            let key = match.first?[1] ?? ""
            keys.insert(key)
            if key == "palette" {
                let value = match.first?[2] ?? ""
                let parts = value.split(separator: "=", maxSplits: 1).map(String.init)
                XCTAssertEqual(parts.count, 2, value)
                if parts.count == 2, let index = Int(parts[0]) {
                    paletteIndices.append(index)
                    XCTAssertNotNil(parts[1].range(of: #"^#[0-9a-f]{6}$"#, options: .regularExpression), value)
                }
            }
        }
        XCTAssertEqual(
            keys,
            [
                "background", "foreground", "cursor-color", "cursor-text",
                "selection-background", "selection-foreground", "palette",
            ]
        )
        XCTAssertEqual(paletteIndices, Array(0..<16))
    }

    // MARK: - zellij

    func testZellijKDLThemeBlock() throws {
        let lines = (try render(.zellij))
            .components(separatedBy: "\n")
            .filter { !$0.isEmpty && !$0.hasPrefix("//") }
        XCTAssertEqual(lines.first, "themes {")
        XCTAssertEqual(lines.last, "}")
        var colours = Set<String>()
        for line in lines {
            if ["themes {", "    palette {", "    }", "}"].contains(line) { continue }
            let match = captures(#"^        ([a-z]+) "(#[0-9a-f]{6})"$"#, in: line)
            XCTAssertEqual(match.count, 1, "KDL line does not parse: \(line)")
            colours.insert(match.first?[1] ?? "")
        }
        XCTAssertEqual(
            colours,
            ["fg", "bg", "black", "red", "green", "yellow", "blue",
             "magenta", "cyan", "white", "orange", "gray"]
        )
        XCTAssertFalse(try render(.zellij).contains("\n#"), "KDL has no # comments")
    }

    // MARK: - Neovim

    func testNvimLuaIsPlainLua() throws {
        let text = try render(.nvim)
        let body = text.components(separatedBy: "\n").filter {
            !$0.isEmpty && !$0.hasPrefix("--")
        }
        XCTAssertTrue(text.contains("vim.g.colors_name = \"palette\""))
        XCTAssertFalse(body.contains { $0.hasPrefix("#") }, "Lua cannot use # comments")
        XCTAssertEqual(body.filter { $0.hasPrefix("hl(\"") }.count, 0)
        // One table, one loop: every group carries fg and/or bg.
        let entries = body.filter { $0.range(of: #"^  [A-Za-z]+ = \{ (fg|bg) = "#, options: .regularExpression) != nil }
        XCTAssertEqual(entries.count, 18)
        XCTAssertTrue(text.filter { $0 == "{" }.count == text.filter { $0 == "}" }.count)
        // Every colour is a quoted hex string, so no Lua escaping is needed.
        for line in body where line.contains("#") {
            XCTAssertNotNil(
                line.range(of: ##""#[0-9a-f]{6}""##, options: .regularExpression),
                line
            )
        }
    }

    func testNvimLuaReappliesAfterColorschemeAndFileChange() throws {
        let text = try render(.nvim)
        // A colorscheme loaded after init.lua (Lazy) must not win.
        XCTAssertTrue(text.contains("local function apply()"))
        XCTAssertTrue(text.contains("vim.api.nvim_create_augroup(\"PaletteTheme\", { clear = true })"))
        XCTAssertTrue(
            text.contains("vim.api.nvim_create_autocmd(\"ColorScheme\", { group = \"PaletteTheme\", callback = apply })")
        )
        // Palette rewrites nvim.lua: watch the directory and debounce.
        XCTAssertTrue(text.contains("uv.new_fs_event()"))
        XCTAssertTrue(text.contains("handle:start(dir, {}, function(err, name)"))
        XCTAssertTrue(text.contains("timer:start(200, 0, vim.schedule_wrap(reload))"))
        XCTAssertTrue(text.contains("pcall(dofile, file)"))
        XCTAssertTrue(text.contains("if not _G.palette_theme_watching then"))
        XCTAssertTrue(text.contains("_G.palette_theme_reloading"))
        // Stop the watcher on exit.
        XCTAssertTrue(text.contains("vim.api.nvim_create_autocmd(\"VimLeavePre\", {"))
        XCTAssertTrue(text.contains("handle:close()"))
        // colors_name belongs to the direct pass, never to the callback.
        XCTAssertEqual(text.components(separatedBy: "vim.g.colors_name").count - 1, 1)
    }

    // MARK: - fish

    func testFishUsesSetCommands() throws {
        let lines = bodyLines(try render(.fish))
        XCTAssertEqual(lines.count, 15)
        for line in lines {
            XCTAssertNotNil(
                line.range(of: #"^set -g fish_color_[a-z_]+( .+)?$"#, options: .regularExpression),
                "fish line does not parse: \(line)"
            )
        }
    }

    // MARK: - Starship

    func testStarshipFilesAreValidTOML() throws {
        let themed = StarshipTheme.render(
            userConfig: """
            palette = "custom"
            format = "$directory$character"

            [character]
            success_symbol = "[>](bold pink)"

            [directory]
            style = "bold blue"

            [palettes.custom]
            pink = "#ff66cc"
            text = "white"
            """,
            palette: palette,
            header: metadata.header
        ).text

        let table = try TOMLTable(string: themed)
        XCTAssertTrue(themed.hasSuffix("\n"), "TOML file should end with a newline")
        XCTAssertEqual(table.str("palette"), "custom")
        // ANSI names in styles are replaced with the palette hex.
        XCTAssertEqual(table.table("directory")?.str("style"), "bold \(palette.ansi[4])")
        // Custom palette names keep their style string but their values snap
        // to the nearest Palette colour.
        XCTAssertEqual(table.table("character")?.str("success_symbol"), "[>](bold pink)")
        let custom = try XCTUnwrap(table.table("palettes")?.table("custom"))
        for key in ["pink", "text"] {
            XCTAssertNotNil(
                custom.str(key)?.range(of: #"^#[0-9a-f]{6}$"#, options: .regularExpression),
                "\(key) was not recoloured: \(custom.str(key) ?? "nil")"
            )
        }
    }

    // MARK: - bat

    func testBatTmThemeIsWellFormedXML() throws {
        let text = try render(.bat)
        XCTAssertTrue(text.hasPrefix("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"))
        let declaration = text.components(separatedBy: "\n").first ?? ""
        XCTAssertTrue(declaration.hasPrefix("<?xml"), "XML declaration must be first")
        for line in text.components(separatedBy: "\n") where line.hasPrefix("<!--") {
            XCTAssertTrue(line.hasSuffix("-->"), line)
        }
        XCTAssertNoThrow(try XMLDocument(xmlString: text))
        let document = try XMLDocument(xmlString: text)
        XCTAssertEqual(document.rootElement()?.name, "plist")
        XCTAssertTrue(text.contains("<key>settings</key>"))
    }

    // MARK: - delta

    func testDeltaGitConfigLines() throws {
        let lines = bodyLines(try render(.delta))
        XCTAssertEqual(lines.first, "[delta]")
        var keys = Set<String>()
        for line in lines.dropFirst() {
            let match = captures(#"^    ([a-z-]+) = (.+)$"#, in: line)
            XCTAssertEqual(match.count, 1, "git config line does not parse: \(line)")
            let key = match.first?[1] ?? ""
            XCTAssertTrue(keys.insert(key).inserted, "duplicate git key \(key)")
            let unquoted = line.replacingOccurrences(
                of: #""[^"]*""#,
                with: "",
                options: .regularExpression
            )
            XCTAssertFalse(unquoted.contains("#"), "a bare # would start a git comment: \(line)")
        }
    }

    // MARK: - btop

    func testBtopThemeUsesOnlyKnownKeys() throws {
        // btop 1.4.8 Default_theme; a key outside it is silently ignored.
        let known = Set([
            "main_bg", "main_fg", "title", "hi_fg", "selected_bg", "selected_fg",
            "inactive_fg", "graph_text", "meter_bg", "proc_misc", "cpu_box",
            "mem_box", "net_box", "proc_box", "div_line", "temp_start", "temp_mid",
            "temp_end", "cpu_start", "cpu_mid", "cpu_end", "free_start", "free_mid",
            "free_end", "cached_start", "cached_mid", "cached_end", "available_start",
            "available_mid", "available_end", "used_start", "used_mid", "used_end",
            "download_start", "download_mid", "download_end", "upload_start",
            "upload_mid", "upload_end", "process_start", "process_mid", "process_end",
            "proc_pause_bg", "proc_follow_bg", "proc_banner_bg", "proc_banner_fg",
            "followed_bg", "followed_fg",
        ])
        var keys = Set<String>()
        for line in bodyLines(try render(.btop)) {
            let match = captures(#"^theme\[([a-z_]+)\]="(#[0-9a-f]{6})"$"#, in: line)
            XCTAssertEqual(match.count, 1, "btop line does not parse: \(line)")
            let key = match.first?[1] ?? ""
            XCTAssertTrue(known.contains(key), "btop ignores \(key)")
            XCTAssertTrue(keys.insert(key).inserted, "duplicate btop key \(key)")
        }
        XCTAssertTrue(keys.contains("download_start"))
        XCTAssertTrue(keys.contains("upload_start"))
        XCTAssertFalse(keys.contains("download"), "bare download/upload keys are ignored")
    }

    // MARK: - yazi

    func testYaziThemeIsTOMLWithCurrentSchema() throws {
        let text = try render(.yazi)
        let table = try TOMLTable(string: text)
        let known: [String: Set<String>] = [
            "mgr": [
                "cwd", "find_keyword", "find_position", "symlink_target", "marker_copied",
                "marker_cut", "marker_marked", "marker_selected", "marker_symbol",
                "count_copied", "count_cut", "count_selected", "border_symbol",
                "border_style", "syntect_theme",
            ],
            "indicator": ["parent", "current", "preview", "padding"],
            "mode": [
                "normal_main", "normal_alt", "select_main", "select_alt",
                "unset_main", "unset_alt",
            ],
            "status": [
                "overall", "sep_left", "sep_right", "perm_sep", "perm_type",
                "perm_read", "perm_write", "perm_exec", "progress_label",
                "progress_normal", "progress_error",
            ],
            "which": [
                "border", "cols", "mask", "cand", "rest", "desc", "separator",
                "separator_style",
            ],
            "filetype": ["rules"],
        ]
        for section in table.keys {
            guard let sectionKeys = known[section] else {
                XCTFail("unknown yazi section [\(section)]")
                continue
            }
            let nested = try XCTUnwrap(table.table(section))
            for key in nested.keys {
                XCTAssertTrue(sectionKeys.contains(key), "unknown yazi key \(section).\(key)")
            }
        }
        XCTAssertNil(table.table("manager"), "yazi renamed [manager] to [mgr]")

        let rules = try XCTUnwrap(table.table("filetype")?["rules"]?.array)
        XCTAssertFalse(rules.isEmpty)
        for rule in rules {
            let mime = try XCTUnwrap(rule.table?.str("mime"))
            XCTAssertTrue(mime.hasPrefix("**/"), "filetype mime needs a **/ glob: \(mime)")
        }
    }

    // MARK: - Chromium managed policy

    func testMobileConfigsAreValidPlistXMLWithUniqueUUIDs() throws {
        var uuids = Set<String>()
        for browser in ChromiumBrowser.catalog where browser.supportsThemePolicy {
            let xml = ChromiumPolicy.mobileConfig(browser: browser, palette: palette)
            XCTAssertTrue(xml.hasPrefix("<?xml version=\"1.0\" encoding=\"UTF-8\"?>"), browser.name)
            XCTAssertNoThrow(try XMLDocument(xmlString: xml), browser.name)

            let data = try XCTUnwrap(xml.data(using: .utf8))
            let plist = try PropertyListSerialization.propertyList(from: data, options: [], format: nil)
            let root = try XCTUnwrap(plist as? [String: Any], browser.name)
            XCTAssertEqual(root["PayloadType"] as? String, "Configuration")
            XCTAssertEqual(root["PayloadIdentifier"] as? String, browser.policyIdentifier)

            let uuid = try XCTUnwrap(root["PayloadUUID"] as? String, browser.name)
            XCTAssertNotNil(UUID(uuidString: uuid), "\(browser.name) UUID is malformed: \(uuid)")
            XCTAssertTrue(uuids.insert(uuid).inserted, "duplicate PayloadUUID \(uuid)")
        }
    }

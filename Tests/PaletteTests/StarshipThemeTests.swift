import TOMLKit
import XCTest
import PaletteCore

/// The themed Starship copy: ANSI names become Palette hex, everything else
/// stays put. TOMLKit drops comments, which the generated header admits.
final class StarshipThemeTests: XCTestCase {
    private let palette = PalettePalette(theme: .defaultDark)
    private let header = "# generated by Palette — do not edit"

    private func render(_ user: String?) -> String {
        StarshipTheme.render(userConfig: user, palette: palette, header: header).text
    }

    func testANSIAndBrightNamesBecomePaletteHex() throws {
        let user = """
        [directory]
        style = "bold blue"

        [git_status]
        style = "fg:bright-red bg:black"

        [character]
        success_symbol = "[>](bold green)"

        [deploy]
        format = "[$symbol](purple)"
        """
        let table = try TOMLTable(string: render(user))

        XCTAssertEqual(table.table("directory")?.str("style"), "bold \(palette.ansi[4])")
        XCTAssertEqual(
            table.table("git_status")?.str("style"),
            "fg:\(palette.ansi[9]) bg:\(palette.ansi[0])"
        )
        XCTAssertEqual(table.table("character")?.str("success_symbol"), "[>](bold \(palette.ansi[2]))")
        XCTAssertEqual(table.table("deploy")?.str("format"), "[$symbol](\(palette.ansi[5]))")
    }

    func testEveryBaseAndBrightNameMapsToItsANSISlot() throws {
        let names = ["black", "red", "green", "yellow", "blue", "purple", "cyan", "white"]
        for (index, name) in names.enumerated() {
            let base = try TOMLTable(string: render("[module]\nstyle = \"\(name)\"\n"))
            XCTAssertEqual(base.table("module")?.str("style"), palette.ansi[index])
            let bright = try TOMLTable(string: render("[module]\nstyle = \"bright-\(name)\"\n"))
            XCTAssertEqual(bright.table("module")?.str("style"), palette.ansi[index + 8])
        }
    }

    func testUnrelatedKeysModulesAndTheUsersOwnPaletteSurvive() throws {
        let user = """
        add_newline = false

        [palettes.mine]
        blue = "#123456"

        [time]
        time_format = "%H:%M"
        style = "bold white"

        [directory]
        truncation_symbol = "…/"
        style = "bold blue"
        """
        let table = try TOMLTable(string: render(user))

        XCTAssertEqual(table.bool("add_newline"), false)
        XCTAssertEqual(table.table("palettes")?.table("mine")?.str("blue"), "#123456")
        XCTAssertEqual(table.table("time")?.str("time_format"), "%H:%M")
        XCTAssertEqual(table.table("time")?.str("style"), "bold \(palette.ansi[7])")
        XCTAssertEqual(table.table("directory")?.str("truncation_symbol"), "…/")
        XCTAssertEqual(table.table("directory")?.str("style"), "bold \(palette.ansi[4])")
    }

    func testCommentsAreDroppedAndTheHeaderSaysSo() {
        let out = render("# keep me\n[directory]\nstyle = \"blue\"\n")

        XCTAssertFalse(out.contains("# keep me"))
        XCTAssertTrue(out.contains("comments are dropped by the TOML round-trip"))
    }

    func testActivePaletteValuesSnapToPaletteColoursAndKeepTheirKeys() throws {
        let user = """
        palette = "noctalia"
        format = "$directory$git_branch"
        "$schema" = "https://starship.rs/config-schema.json"

        [directory]
        style = "fg:pink bold"

        [git_branch]
        style = "fg:text"

        [git_status]
        style = "fg:flamingo"

        [time]
        style = "fg:subtext0"

        [palettes.noctalia]
        pink = "#ffacea"
        text = "#f2dde8"
        flamingo = "#ffb4ab"
        subtext0 = "#a28a99"
        """
        let table = try TOMLTable(string: render(user))
        let paletteTable = try XCTUnwrap(table.table("palettes")?.table("noctalia"))
        let originals = [
            "pink": "#ffacea",
            "text": "#f2dde8",
            "flamingo": "#ffb4ab",
            "subtext0": "#a28a99",
        ]
        let allowed = Set(
            [palette.background, palette.foreground, palette.cursor, palette.selectionBackground, palette.selectionForeground]
                + palette.ansi
        )

        XCTAssertEqual(Set(paletteTable.keys), Set(originals.keys))
        for (key, original) in originals {
            let mapped = try XCTUnwrap(paletteTable.str(key))
            XCTAssertNotEqual(mapped, original, "\(key) was not recoloured")
            XCTAssertTrue(allowed.contains(mapped), "\(key) mapped to \(mapped), outside the Palette colours")
        }

        // The modules keep their custom names; only the palette values moved.
        XCTAssertEqual(table.table("directory")?.str("style"), "fg:pink bold")
        XCTAssertEqual(table.table("git_branch")?.str("style"), "fg:text")
        XCTAssertEqual(table.table("git_status")?.str("style"), "fg:flamingo")
        XCTAssertEqual(table.table("time")?.str("style"), "fg:subtext0")
        XCTAssertEqual(table.str("palette"), "noctalia")
        XCTAssertEqual(table.str("format"), "$directory$git_branch")
    }

    /// Keys named after terminal colours keep that meaning; only custom names
    /// snap to the nearest colour. A near-monochrome wallpaper palette used to
    /// collapse `blue` and `bright-blue` into the same grey.
    func testNamedPaletteKeysFollowTheirAnsiSlot() throws {
        let user = """
        palette = "palette"

        [palettes.palette]
        fg = "#ffffff"
        bg = "#000000"
        accent = "#ff0000"
        blue = "#89b4fa"
        bright-blue = "#89b4fa"
        bright-cyan = "#89b4fa"
        pink = "#ffacea"
        """
        let table = try TOMLTable(string: render(user))
        let values = try XCTUnwrap(table.table("palettes")?.table("palette"))
        XCTAssertEqual(values.str("fg"), palette.foreground)
        XCTAssertEqual(values.str("bg"), palette.background)
        XCTAssertEqual(values.str("accent"), palette.cursor)
        XCTAssertEqual(values.str("blue"), palette.ansi[4])
        XCTAssertEqual(values.str("bright-blue"), palette.ansi[12])
        XCTAssertEqual(values.str("bright-cyan"), palette.ansi[14])
        XCTAssertNotEqual(values.str("blue"), values.str("bright-blue"))
        XCTAssertNotEqual(values.str("pink"), palette.ansi[4], "custom names still snap")
    }

    func testActivePaletteValuesFollowTheTheme() throws {
        let user = """
        palette = "noctalia"

        [palettes.noctalia]
        pink = "#ffacea"
        text = "#f2dde8"
        flamingo = "#ffb4ab"
        subtext0 = "#a28a99"
        """
        func values(_ palette: PalettePalette) throws -> [String: String] {
            let table = try TOMLTable(string: StarshipTheme.render(
                userConfig: user,
                palette: palette,
                header: header
            ).text)
            let values = try XCTUnwrap(table.table("palettes")?.table("noctalia"))
            return Dictionary(uniqueKeysWithValues: values.keys.map { ($0, values.str($0) ?? "") })
        }

        let dark = try values(PalettePalette(theme: .defaultDark))
        let light = try values(PalettePalette(theme: .defaultLight))

        XCTAssertEqual(Set(dark.keys), Set(light.keys))
        XCTAssertNotEqual(dark, light)
    }

    func testConfigWithoutPaletteStillGetsTheANSIRemap() throws {
        let table = try TOMLTable(string: render("[directory]\nstyle = \"bold blue\"\n"))

        XCTAssertEqual(table.table("directory")?.str("style"), "bold \(palette.ansi[4])")
    }

    func testHexAndUnknownNamesAreLeftAlone() throws {
        let user = """
        [directory]
        style = "#abcdef bold"
        format = "blueish"
        """
        let table = try TOMLTable(string: render(user))

        XCTAssertEqual(table.table("directory")?.str("style"), "#abcdef bold")
        XCTAssertEqual(table.table("directory")?.str("format"), "blueish")
    }

    func testMissingConfigUsesTheMinimalDefault() throws {
        let result = StarshipTheme.render(userConfig: nil, palette: palette, header: header)

        XCTAssertNotNil(result.notice)
        let table = try TOMLTable(string: result.text)
        XCTAssertEqual(table.table("character")?.str("success_symbol"), "[❯](bold \(palette.ansi[2]))")
        XCTAssertEqual(table.table("directory")?.str("style"), "bold \(palette.ansi[4])")
    }

    func testInvalidConfigFallsBackToTheMinimalDefault() throws {
        let result = StarshipTheme.render(userConfig: "this is not = = toml", palette: palette, header: header)

        XCTAssertTrue(result.notice?.contains("not valid TOML") == true)
        let table = try TOMLTable(string: result.text)
        XCTAssertEqual(table.table("directory")?.str("style"), "bold \(palette.ansi[4])")
    }
}

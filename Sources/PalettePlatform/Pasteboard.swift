import AppKit
import CryptoKit
import ImageIO
import PaletteCore

public enum ClipboardCapture: Sendable {
    case text(String)
    case image(png: Data, thumbnail: Data?, width: Int, height: Int)
    case files(paths: [String], thumbnail: Data?)
}

public final class ClipboardMonitor: @unchecked Sendable {
    private let pasteboard = NSPasteboard.general
    private let queue = DispatchQueue(label: "dev.myleshen.palette.clipboard")
    private var timer: DispatchSourceTimer?
    private var lastChangeCount: Int
    private var intervalMs: Int = 500

    public var onCapture: (@Sendable (ClipboardCapture) -> Void)?

    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    public init() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    public func start(intervalMs: Int) {
        stop()
        self.intervalMs = max(150, intervalMs)
        lastChangeCount = pasteboard.changeCount
        let timer = DispatchSource.makeTimerSource(queue: queue)
        timer.schedule(deadline: .now() + .milliseconds(self.intervalMs), repeating: .milliseconds(self.intervalMs))
        timer.setEventHandler { [weak self] in
            self?.poll()
        }
        timer.resume()
        self.timer = timer
    }

    public func stop() {
        timer?.cancel()
        timer = nil
    }

    public func captureNow() {
        queue.async { [weak self] in
            self?.poll(force: true)
        }
    }

    private func poll(force: Bool = false) {
        let current = pasteboard.changeCount
        guard force || current != lastChangeCount else { return }
        lastChangeCount = current

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        // Finder copies carry file URLs *and* a text representation of the
        // names, so files must be checked before plain text.
        if let paths = Self.filePaths(from: pasteboard) {
            onCapture?(.files(paths: paths, thumbnail: Self.fileThumbnail(paths.first)))
            return
        }

        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            guard text.utf8.count <= 1_000_000 else { return }
            onCapture?(.text(text))
            return
        }

        guard let image = Self.imageData(from: pasteboard) else { return }
        onCapture?(.image(
            png: image.data,
            thumbnail: Self.thumbnailPNG(from: image.data),
            width: image.width,
            height: image.height
        ))
    }

    private static func filePaths(from pasteboard: NSPasteboard) -> [String]? {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        guard let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL] else { return nil }
        let paths = urls.filter(\.isFileURL).map { $0.path }
        return paths.isEmpty ? nil : paths
    }

    private static func fileThumbnail(_ path: String?) -> Data? {
        guard let path else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: path)
        icon.size = NSSize(width: 128, height: 128)
        guard let tiff = icon.tiffRepresentation,
              let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }

    private static func imageData(from pasteboard: NSPasteboard) -> (data: Data, width: Int, height: Int)? {
        let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff)
        guard let data, !data.isEmpty, data.count <= 20_000_000,
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0 else { return nil }
        return (data, width, height)
    }

    private static func thumbnailPNG(from data: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 320,
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
    }
}

@MainActor
public final class PasteboardService {
    private var clearWorkItem: DispatchWorkItem?
    private var writtenChangeCount: Int = -1

    public init() {}

    public var isAccessibilityTrusted: Bool {
        AXIsProcessTrusted()
    }

    public func requestAccessibility() {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }

    @discardableResult
    public func write(text: String, concealed: Bool = false, clearAfterMs: Int? = nil) -> Int {
        clearWorkItem?.cancel()
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if concealed {
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        }
        pasteboard.writeObjects([item])
        let changeCount = pasteboard.changeCount
        writtenChangeCount = changeCount

        if let clearAfterMs, clearAfterMs > 0 {
            scheduleClear(changeCount: changeCount, clearAfterMs: clearAfterMs)
        }
        return changeCount
    }

    @discardableResult
    public func write(image: Data, concealed: Bool = false, clearAfterMs: Int? = nil) -> Int {
        clearWorkItem?.cancel()
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        let item = NSPasteboardItem()
        item.setData(image, forType: .png)
        if let tiff = NSImage(data: image)?.tiffRepresentation {
            item.setData(tiff, forType: .tiff)
        }
        if concealed {
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        }
        pasteboard.writeObjects([item])
        let changeCount = pasteboard.changeCount
        writtenChangeCount = changeCount

        if let clearAfterMs, clearAfterMs > 0 {
            scheduleClear(changeCount: changeCount, clearAfterMs: clearAfterMs)
        }
        return changeCount
    }

    @discardableResult
    public func write(files paths: [String], concealed: Bool = false, clearAfterMs: Int? = nil) -> Int {
        clearWorkItem?.cancel()
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.writeObjects(paths.map { URL(fileURLWithPath: $0) as NSURL })
        let changeCount = pasteboard.changeCount
        writtenChangeCount = changeCount

        if let clearAfterMs, clearAfterMs > 0 {
            scheduleClear(changeCount: changeCount, clearAfterMs: clearAfterMs)
        }
        return changeCount
    }

    private func scheduleClear(changeCount: Int, clearAfterMs: Int) {
        let work = DispatchWorkItem { [weak self] in
            guard let self else { return }
            if NSPasteboard.general.changeCount == changeCount {
                NSPasteboard.general.clearContents()
            }
            self.clearWorkItem = nil
        }
        clearWorkItem = work
        DispatchQueue.main.asyncAfter(deadline: .now() + .milliseconds(clearAfterMs), execute: work)
    }

    /// Copies and, when Accessibility is granted, pastes into the given app.
    /// Returns false when the paste keystroke could not be delivered.
    @discardableResult
    public func paste(text: String, concealed: Bool = false, into app: NSRunningApplication?) -> Bool {
        write(text: text, concealed: concealed)
        return deliver(to: app)
    }

    @discardableResult
    public func paste(image: Data, concealed: Bool = false, into app: NSRunningApplication?) -> Bool {
        write(image: image, concealed: concealed)
        // TUI editors such as OpenCode read images from the clipboard when
        // they receive Ctrl+V; Cmd+V only reaches the terminal's text paste.
        return deliver(to: app, modifiers: Self.imagePasteModifiers(for: app))
    }

    @discardableResult
    public func paste(files paths: [String], into app: NSRunningApplication?) -> Bool {
        write(files: paths)
        return deliver(to: app)
    }

    private func deliver(to app: NSRunningApplication?, modifiers: CGEventFlags = .maskCommand) -> Bool {
        guard isAccessibilityTrusted else {
            Log.shared.warn("Paste skipped: Accessibility is not trusted", source: "clipboard")
            requestAccessibility()
            return false
        }

        guard let app, !app.isTerminated else {
            Log.shared.warn("Paste skipped: the previous application is gone", source: "clipboard")
            return false
        }

        Log.shared.info(
            "Paste requested target=\(app.localizedName ?? "nil") modifiers=\(modifiers.rawValue) trusted=\(isAccessibilityTrusted)",
            source: "clipboard"
        )
        // Hand focus back explicitly. Without yielding, macOS may keep Palette
        // active and the synthetic paste goes to the launcher instead of the
        // terminal/editor behind it.
        NSApp.yieldActivation(to: app)
        activate(app)
        waitForActivation(of: app, modifiers: modifiers, attempt: 0)
        return true
    }

    private func activate(_ app: NSRunningApplication) {
        if app.isHidden { app.unhide() }
        app.activate(options: [.activateAllWindows])
    }

    /// Activation is asynchronous, and 0.22 s was not enough after hiding the
    /// panel. Poll until the target is frontmost, then give the window a beat
    /// before posting the key.
    private func waitForActivation(
        of app: NSRunningApplication,
        modifiers: CGEventFlags,
        attempt: Int
    ) {
        let front = NSWorkspace.shared.frontmostApplication
        if front?.processIdentifier == app.processIdentifier || attempt >= 20 {
            Log.shared.info(
                "Paste delivering target=\(app.localizedName ?? "nil") frontmost=\(front?.localizedName ?? "nil")",
                source: "clipboard"
            )
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
                Self.sendPaste(modifiers: modifiers)
            }
            return
        }

        if attempt % 4 == 0 {
            NSApp.yieldActivation(to: app)
            activate(app)
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) { [weak self] in
            self?.waitForActivation(of: app, modifiers: modifiers, attempt: attempt + 1)
        }
    }

    private static func imagePasteModifiers(for app: NSRunningApplication?) -> CGEventFlags {
        let terminalBundleIDs: Set<String> = [
            "net.kovidgoyal.kitty",
            "com.apple.Terminal",
            "com.googlecode.iterm2",
            "dev.wez.wezterm",
            "org.alacritty",
            "com.mitchellh.ghostty",
            "co.zeit.hyper",
        ]
        if let id = app?.bundleIdentifier, terminalBundleIDs.contains(id) {
            return .maskControl
        }
        return .maskCommand
    }

    private static func sendPaste(modifiers: CGEventFlags) {
        guard let source = CGEventSource(stateID: .hidSystemState) else { return }
        let keyCode: CGKeyCode = 9 // V
        if let down = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true) {
            down.flags = modifiers
            down.post(tap: .cghidEventTap)
        }
        if let up = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false) {
            up.flags = modifiers
            up.post(tap: .cghidEventTap)
        }
    }
}

import AppKit
import ApplicationServices
import CryptoKit
import ImageIO
import PaletteCore

public enum ClipboardCapture: Sendable {
    case text(String)
    case image(png: Data, thumbnail: Data?, width: Int, height: Int)
    case files(paths: [String], thumbnail: Data?)
}

public final class ClipboardMonitor: @unchecked Sendable {
    private let pasteboard = NSPasteboard.general
    private let queue = DispatchQueue(label: "dev.myleshen.palette.clipboard")
    private var timer: DispatchSourceTimer?
    private var lastChangeCount: Int
    private var intervalMs: Int = 500

    public var onCapture: (@Sendable (ClipboardCapture) -> Void)?

    /// Bundle ids whose copies are never recorded. Read from the poll queue, so
    /// changes go through a lock rather than racing a Settings save.
    private let ignoredAppsLock = NSLock()
    private var ignoredApps: Set<String> = []

    public func setIgnoredApps(_ bundleIDs: [String]) {
        ignoredAppsLock.lock()
        ignoredApps = Set(bundleIDs)
        ignoredAppsLock.unlock()
    }

    /// Change counts Palette wrote itself. Their content is already in history
    /// (or is a save-copy screenshot), so recording it again is noise.
    nonisolated(unsafe) private static var paletteWrite: Int = -1
    private static let paletteWriteLock = NSLock()

    public static func notePaletteWrite(_ changeCount: Int) {
        paletteWriteLock.lock()
        paletteWrite = changeCount
        paletteWriteLock.unlock()
    }

    private static func consumePaletteWrite(_ changeCount: Int) -> Bool {
        paletteWriteLock.lock()
        defer { paletteWriteLock.unlock() }
        guard paletteWrite == changeCount else { return false }
        paletteWrite = -1
        return true
    }

    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    public init() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    public func start(intervalMs: Int, preserveChangeCount: Bool = false) {
        stop()
        self.intervalMs = max(150, intervalMs)
        // A reload restarts polling; keep the last seen count so a copy made
        // during the reload window is still captured. A cold start must skip
        // whatever was already on the clipboard.
        if !preserveChangeCount {
            lastChangeCount = pasteboard.changeCount
        }
        let timer = DispatchSource.makeTimerSource(queue: queue)
        timer.schedule(deadline: .now() + .milliseconds(self.intervalMs), repeating: .milliseconds(self.intervalMs))
        timer.setEventHandler { [weak self] in
            self?.poll()
        }
        timer.resume()
        self.timer = timer
    }

    public func stop() {
        timer?.cancel()
        timer = nil
    }

    public func captureNow() {
        queue.async { [weak self] in
            self?.poll(force: true)
        }
    }

    private func poll(force: Bool = false) {
        // Sampled every poll: a copy is attributed to whichever app is
        // frontmost when the pasteboard changes, so the ignore list is checked
        // against that app rather than the one that happened to launch Palette.
        let frontmostBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let current = pasteboard.changeCount
        guard force || current != lastChangeCount else { return }
        lastChangeCount = current
        guard !Self.consumePaletteWrite(current) else { return }

        let types = Set(pasteboard.types ?? [])
        ignoredAppsLock.lock()
        let ignored = ignoredApps
        ignoredAppsLock.unlock()
        guard ClipboardCapturePolicy.shouldCapture(
            frontmostBundleID: frontmostBundleID,
            ignoredApps: ignored,
            isMarkedSecret: !types.isDisjoint(with: Self.ignoredTypes)
        ) else { return }

        // Finder copies carry file URLs *and* a text representation of the
        // names, so files must be checked before plain text.
        if let paths = Self.filePaths(from: pasteboard) {
            onCapture?(.files(paths: paths, thumbnail: Self.fileThumbnail(paths.first)))
            return
        }

        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            guard text.utf8.count <= 1_000_000 else { return }
            onCapture?(.text(text))
            return
        }

        guard let image = Self.imageData(from: pasteboard) else { return }
        onCapture?(.image(
            png: image.data,
            thumbnail: Self.thumbnailPNG(from: image.data),
            width: image.width,
            height: image.height
        ))
    }

    private static func filePaths(from pasteboard: NSPasteboard) -> [String]? {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        guard let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL] else { return nil }
        let paths = urls.filter(\.isFileURL).map { $0.path }
        return paths.isEmpty ? nil : paths
    }

    static func fileThumbnail(_ path: String?) -> Data? {
        guard let path else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: path)
        icon.size = NSSize(width: 128, height: 128)
        guard let tiff = icon.tiffRepresentation,
              let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }

    private static func imageData(from pasteboard: NSPasteboard) -> (data: Data, width: Int, height: Int)? {
        let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff)
        guard let data, !data.isEmpty, data.count <= 20_000_000,
              let size = imageSize(of: data) else { return nil }
        return (data, size.width, size.height)
    }

    /// Pixel size of image bytes from the pasteboard or a file Palette saved.
    static func imageSize(of data: Data) -> (width: Int, height: Int)? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0 else { return nil }
        return (width, height)
    }

    static func thumbnailPNG(from data: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 320,
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
    }
}

/// A clipboard clear that has to survive quitting Palette: the secret's
/// deadline, its SHA-256, and the pasteboard changeCount at write time.
struct PendingClipboardClear: Codable, Equatable, Sendable {
    var expiresAt: Double
    var hash: String
    var changeCount: Int

    func isDue(at date: Date = Date()) -> Bool {
        expiresAt <= date.timeIntervalSince1970
    }

    /// Only the recorded value is cleared. An unrelated clipboard survives.
    func shouldClear(currentHash: String?, at date: Date = Date()) -> Bool {
        isDue(at: date) && currentHash == hash
    }
}

/// What happened after the clipboard was written. `.pasted` means the target
/// took focus and the delivery was scheduled; it is only returned after the
/// activation poll succeeds.
public enum PasteOutcome: Equatable, Sendable {
    /// A menu press or keystroke was scheduled for the target.
    case pasted
    /// Clipboard written; the target would mangle an injected shortcut.
    case copiedOnly
    /// Clipboard written; Accessibility is missing so nothing was injected.
    case needsAccessibility
    /// Clipboard written; there is no previous app to paste into.
    case noTarget
    /// Clipboard written; the target never came forward, so nothing was typed.
    case activationFailed
}

public extension PasteOutcome {
    /// Text the host shows when the clipboard was written but no paste was
    /// delivered. Nil means the panel may hide.
    var fallbackStatus: String? {
        switch self {
        case .pasted: return nil
        case .copiedOnly, .noTarget: return "Copied — paste with ⌘V"
        case .needsAccessibility: return "Copied — enable Accessibility to paste automatically."
        case .activationFailed: return "Could not paste — the target app did not come forward; press ⌘V"
        }
    }
}

@MainActor
public final class PasteboardService {
    private var clearWorkItem: DispatchWorkItem?
    private var writtenChangeCount: Int = -1
    /// `stateDir/clipboard-clear.json`. Nil keeps clears in memory only.
    public var stateFile: URL?
    /// Tests drive paste scheduling without triggering the Accessibility prompt.
    var requestsAccessibility = true
    /// Tests pin the trust answer instead of depending on the runner's grant.
    var accessibilityTrustedOverride: Bool?
    /// Tests pin the frontmost answer so activation can be driven headlessly.
    var frontmostApplicationOverride: (() -> NSRunningApplication?)?
    /// Tests poll faster than the real 50 ms.
    var activationPollMilliseconds = 50
    /// Every clipboard write, so a test can prove a paste writes only once.
    private(set) var writes = 0

    public init() {}

    /// Called on launch before any write: clear a secret whose deadline passed
    /// while Palette was closed, or re-arm the remaining time.
    public func resumePendingClear(now: Date = Date()) {
        guard let record = readPendingClear() else { return }
        if record.shouldClear(currentHash: Self.fingerprint(), at: now) {
            NSPasteboard.general.clearContents()
            Log.shared.info("Cleared a clipboard value left over from a previous run", source: "clipboard")
            clearPendingClear()
            return
        }
        if record.isDue(at: now) {
            // The value on the pasteboard is no longer the one we wrote.
            clearPendingClear()
            return
        }
        scheduleClear(
            changeCount: record.changeCount,
            expiresAt: Date(timeIntervalSince1970: record.expiresAt)
        )
    }

    public var isAccessibilityTrusted: Bool {
        accessibilityTrustedOverride ?? AXIsProcessTrusted()
    }

    public func requestAccessibility() {
        // Native by necessity: macOS owns the TCC permission prompt.
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }

    @discardableResult
    public func write(text: String, concealed: Bool = false, clearAfterMs: Int? = nil) -> Int {
        writes += 1
        cancelPendingClear()
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if concealed {
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        }
        pasteboard.writeObjects([item])
        let changeCount = pasteboard.changeCount
        writtenChangeCount = changeCount
        ClipboardMonitor.notePaletteWrite(changeCount)

        if let clearAfterMs, clearAfterMs > 0 {
            scheduleClear(
                changeCount: changeCount,
                expiresAt: Date().addingTimeInterval(Double(clearAfterMs) / 1000),
                hash: Self.digest(Data(text.utf8))
            )
        }
        return changeCount
    }

    @discardableResult
    public func write(image: Data, concealed: Bool = false, clearAfterMs: Int? = nil) -> Int {
        writes += 1
        cancelPendingClear()
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        let item = NSPasteboardItem()
        item.setData(image, forType: .png)
        if let tiff = NSImage(data: image)?.tiffRepresentation {
            item.setData(tiff, forType: .tiff)
        }
        if concealed {
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        }
        pasteboard.writeObjects([item])
        let changeCount = pasteboard.changeCount
        writtenChangeCount = changeCount
        ClipboardMonitor.notePaletteWrite(changeCount)

        if let clearAfterMs, clearAfterMs > 0 {
            scheduleClear(
                changeCount: changeCount,
                expiresAt: Date().addingTimeInterval(Double(clearAfterMs) / 1000),
                hash: Self.digest(image)
            )
        }
        return changeCount
    }

    @discardableResult
    public func write(files paths: [String], concealed: Bool = false, clearAfterMs: Int? = nil) -> Int {
        writes += 1
        cancelPendingClear()
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.writeObjects(paths.map { URL(fileURLWithPath: $0) as NSURL })
        let changeCount = pasteboard.changeCount
        writtenChangeCount = changeCount
        ClipboardMonitor.notePaletteWrite(changeCount)

        if let clearAfterMs, clearAfterMs > 0 {
            scheduleClear(
                changeCount: changeCount,
                expiresAt: Date().addingTimeInterval(Double(clearAfterMs) / 1000),
                hash: Self.digest(Data(paths.joined(separator: "\0").utf8))
            )
        }
        return changeCount
    }

    private func scheduleClear(changeCount: Int, expiresAt: Date, hash: String) {
        persistPendingClear(PendingClipboardClear(
            expiresAt: expiresAt.timeIntervalSince1970,
            hash: hash,
            changeCount: changeCount
        ))
        scheduleClear(changeCount: changeCount, expiresAt: expiresAt)
    }

    private func scheduleClear(changeCount: Int, expiresAt: Date) {
        let delay = max(0, expiresAt.timeIntervalSinceNow)
        let work = DispatchWorkItem { [weak self] in
            guard let self else { return }
            if NSPasteboard.general.changeCount == changeCount {
                NSPasteboard.general.clearContents()
            }
            self.clearWorkItem = nil
            self.clearPendingClear()
        }
        clearWorkItem = work
        DispatchQueue.main.asyncAfter(deadline: .now() + delay, execute: work)
    }

    private func cancelPendingClear() {
        clearWorkItem?.cancel()
        clearWorkItem = nil
        clearPendingClear()
    }

    private func persistPendingClear(_ record: PendingClipboardClear) {
        guard let stateFile else { return }
        do {
            let data = try JSONEncoder().encode(record)
            try data.write(to: stateFile, options: .atomic)
            try FileManager.default.setAttributes(
                [.posixPermissions: 0o600],
                ofItemAtPath: stateFile.path
            )
        } catch {
            Log.shared.warn("Could not persist the clipboard clear: \(error.localizedDescription)", source: "clipboard")
        }
    }

    private func readPendingClear() -> PendingClipboardClear? {
        guard let stateFile,
              let data = try? Data(contentsOf: stateFile) else { return nil }
        guard let record = try? JSONDecoder().decode(PendingClipboardClear.self, from: data) else {
            try? FileManager.default.removeItem(at: stateFile)
            return nil
        }
        return record
    }

    private func clearPendingClear() {
        guard let stateFile else { return }
        try? FileManager.default.removeItem(at: stateFile)
    }

    /// SHA-256 of the pasteboard's current value in the same shape the writes
    /// above use. Files come before text because Finder copies carry both.
    nonisolated static func fingerprint(of pasteboard: NSPasteboard = .general) -> String? {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL],
           !urls.filter(\.isFileURL).isEmpty {
            let paths = urls.filter(\.isFileURL).map(\.path)
            return digest(Data(paths.joined(separator: "\0").utf8))
        }
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            return digest(Data(text.utf8))
        }
        if let image = pasteboard.data(forType: .png) {
            return digest(image)
        }
        if let image = pasteboard.data(forType: .tiff) {
            return digest(image)
        }
        return nil
    }

    nonisolated static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    /// Copies and, when Accessibility is granted, hands the clipboard to the
    /// given app. `route` is resolved here only when the caller did not.
    @discardableResult
    public func paste(
        text: String,
        concealed: Bool = false,
        clearAfterMs: Int? = nil,
        into app: NSRunningApplication?,
        route: PasteTarget.Route? = nil
    ) async -> PasteOutcome {
        write(text: text, concealed: concealed, clearAfterMs: clearAfterMs)
        return await deliver(to: app, route: route)
    }

    @discardableResult
    public func paste(
        image: Data,
        concealed: Bool = false,
        clearAfterMs: Int? = nil,
        into app: NSRunningApplication?,
        route: PasteTarget.Route? = nil
    ) async -> PasteOutcome {
        write(image: image, concealed: concealed, clearAfterMs: clearAfterMs)
        // TUI editors such as OpenCode read images from the clipboard when
        // they receive Ctrl+V; Cmd+V only reaches the terminal's text paste.
        return await deliver(to: app, route: route, modifiers: Self.imagePasteModifiers(for: app), isImage: true)
    }

    @discardableResult
    public func paste(
        files paths: [String],
        clearAfterMs: Int? = nil,
        into app: NSRunningApplication?,
        route: PasteTarget.Route? = nil
    ) async -> PasteOutcome {
        write(files: paths, clearAfterMs: clearAfterMs)
        return await deliver(to: app, route: route)
    }

    private func deliver(
        to app: NSRunningApplication?,
        route: PasteTarget.Route?,
        modifiers: CGEventFlags = .maskCommand,
        isImage: Bool = false
    ) async -> PasteOutcome {
        guard isAccessibilityTrusted else {
            Log.shared.warn("Paste skipped: Accessibility is not trusted", source: "clipboard")
            if requestsAccessibility { requestAccessibility() }
            return .needsAccessibility
        }

        // An explicit copy-only route needs no live target: writing the
        // clipboard is all that happens.
        if route == .copyOnly {
            Log.shared.info("Paste copied only (no synthetic shortcut)", source: "clipboard")
            return .copiedOnly
        }

        guard let app, !app.isTerminated else {
            Log.shared.warn("Paste skipped: the previous application is gone", source: "clipboard")
            return .noTarget
        }

        let route = route ?? PasteTarget.route(
            bundleID: app.bundleIdentifier,
            menuAvailable: Self.canPasteViaMenu(into: app),
            image: isImage
        )
        guard route != .copyOnly else {
            Log.shared.info("Paste copied only target=\(app.localizedName ?? "nil")", source: "clipboard")
            return .copiedOnly
        }

        Log.shared.info(
            "Paste requested target=\(app.localizedName ?? "nil") route=\(route) modifiers=\(modifiers.rawValue)",
            source: "clipboard"
        )
        // Hand focus back explicitly. Without yielding, macOS may keep Palette
        // active and the synthetic paste goes to the launcher instead of the
        // terminal/editor behind it.
        NSApplication.shared.yieldActivation(to: app)
        activate(app)
        guard await waitForActivation(of: app, route: route, modifiers: modifiers, attempt: 0) else {
            return .activationFailed
        }
        return .pasted
    }

    /// True when the app exposes an enabled Edit ▸ Paste item (⌘V).
    public func canPasteViaMenu(into app: NSRunningApplication?) -> Bool {
        guard let app, !app.isTerminated else { return false }
        return Self.canPasteViaMenu(into: app)
    }

    private func activate(_ app: NSRunningApplication) {
        if app.isHidden { app.unhide() }
        app.activate(options: [.activateAllWindows])
    }

    /// Activation is asynchronous, and 0.22 s was not enough after hiding the
    /// panel. Poll until the target is frontmost, then give the window a beat.
    /// Palette must never still be frontmost when the key or menu press goes
    /// out, so a target that never takes focus is abandoned rather than typed
    /// into whatever is in front. Returns false when the budget ran out.
    private func waitForActivation(
        of app: NSRunningApplication,
        route: PasteTarget.Route,
        modifiers: CGEventFlags,
        attempt: Int
    ) async -> Bool {
        let front = frontmostApplication()
        if front?.processIdentifier == app.processIdentifier {
            Log.shared.info(
                "Paste delivering target=\(app.localizedName ?? "nil") route=\(route)",
                source: "clipboard"
            )
            try? await Task.sleep(for: .milliseconds(120))
            Self.perform(route: route, in: app, modifiers: modifiers)
            return true
        }

        if attempt >= 20 {
            Log.shared.warn(
                "Paste aborted: \(app.localizedName ?? "target") did not take focus (frontmost=\(front?.localizedName ?? "nil"))",
                source: "clipboard"
            )
            return false
        }

        if attempt % 4 == 0 {
            NSApplication.shared.yieldActivation(to: app)
            activate(app)
        }
        try? await Task.sleep(for: .milliseconds(activationPollMilliseconds))
        return await waitForActivation(of: app, route: route, modifiers: modifiers, attempt: attempt + 1)
    }

    private func frontmostApplication() -> NSRunningApplication? {
        frontmostApplicationOverride?() ?? NSWorkspace.shared.frontmostApplication
    }

    private static func perform(route: PasteTarget.Route, in app: NSRunningApplication, modifiers: CGEventFlags) {
        if route == .menu, pressPasteMenuItem(in: app) {
            Log.shared.info("Paste delivered via the Edit menu", source: "clipboard")
            return
        }
        // Neovide must not get a bare ⌘V: it would hand nvim `<d+v>`. It keeps
        // the clipboard-only behaviour when the menu press did not work.
        if let bundleID = app.bundleIdentifier, PasteTarget.copyOnlyWhenNoMenuBundleIDs.contains(bundleID) {
            Log.shared.warn("Paste skipped: no usable Edit menu in \(bundleID)", source: "clipboard")
            return
        }
        sendPaste(modifiers: modifiers)
    }

    // MARK: - Edit ▸ Paste through Accessibility

    private static func canPasteViaMenu(into app: NSRunningApplication) -> Bool {
        findPasteMenuItem(in: app) != nil
    }

    @discardableResult
    private static func pressPasteMenuItem(in app: NSRunningApplication) -> Bool {
        guard let item = findPasteMenuItem(in: app) else { return false }
        return AXUIElementPerformAction(item, kAXPressAction as CFString) == .success
    }

    /// The app's Edit menu item that owns ⌘V. Matched by shortcut rather than
    /// title so a localised menu ("Bearbeiten ▸ Einsetzen") still resolves.
    private static func findPasteMenuItem(in app: NSRunningApplication) -> AXUIElement? {
        let appElement = AXUIElementCreateApplication(app.processIdentifier)
        AXUIElementSetMessagingTimeout(appElement, 0.5) // a hung target must not freeze the panel
        guard let menuBar = elementAttribute(appElement, kAXMenuBarAttribute),
              let barItems = attribute(menuBar, kAXChildrenAttribute) as? [AXUIElement] else {
            return nil
        }
        for barItem in barItems {
            guard let menu = (attribute(barItem, kAXChildrenAttribute) as? [AXUIElement])?.first,
                  let items = attribute(menu, kAXChildrenAttribute) as? [AXUIElement] else { continue }
            if let paste = items.first(where: isPasteItem) { return paste }
        }
        return nil
    }

    private static func isPasteItem(_ item: AXUIElement) -> Bool {
        // ⌘ only: shift, option and control are off in the AX modifier sum.
        let modifiers = attribute(item, kAXMenuItemCmdModifiersAttribute) as? Int ?? -1
        guard attribute(item, kAXMenuItemCmdCharAttribute) as? String == "v",
              modifiers & 0b111 == 0,
              attribute(item, kAXEnabledAttribute) as? Bool == true else { return false }
        return true
    }

    private static func elementAttribute(_ element: AXUIElement, _ name: String) -> AXUIElement? {
        guard let value = attribute(element, name),
              CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        return (value as! AXUIElement)
    }

    private static func attribute(_ element: AXUIElement, _ name: String) -> CFTypeRef? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, name as CFString, &value) == .success else { return nil }
        return value
    }

    private static func imagePasteModifiers(for app: NSRunningApplication?) -> CGEventFlags {
        if let id = app?.bundleIdentifier, PasteTarget.imageControlPasteBundleIDs.contains(id) {
            return .maskControl
        }
        return .maskCommand
    }

    private static func sendPaste(modifiers: CGEventFlags) {
        guard let source = CGEventSource(stateID: .hidSystemState) else { return }
        let keyCode: CGKeyCode = 9 // V
        if let down = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true) {
            down.flags = modifiers
            down.post(tap: .cghidEventTap)
        }
        if let up = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false) {
            up.flags = modifiers
            up.post(tap: .cghidEventTap)
        }
    }
}

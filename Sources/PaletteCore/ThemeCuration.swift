    public static func replacement(for id: String) -> String? { pruned[id] }

    /// Rewrites every stored reference to a pruned id. `notes` names what
    /// moved and where the fallback went, so launch can log and show it.
    ///
    /// A reference that still resolves is a user's own theme with a pruned
    /// id; it is left alone.
    @discardableResult
    public static func migrate(
        _ config: inout PaletteConfig,
        themesDirectory: URL,
        bundledThemesDirectory: URL? = ThemeLoader.bundledThemesDirectory,
        favourites: ThemeCardFavourites = ThemeCardFavourites()
    ) -> [String] {
        var notes: [String] = []

        func resolves(_ reference: String) -> Bool {
            ThemeLoader.themeID(
                for: reference,
                themesDirectory: themesDirectory,
                bundledThemesDirectory: bundledThemesDirectory
            ) != nil
        }

        func mapped(_ reference: String, _ label: String) -> String {
            guard !reference.isEmpty, !resolves(reference),
                  let target = pruned[reference] else { return reference }
            notes.append(target.hasPrefix("default-")
                ? "\(label) '\(reference)' has no curated sibling; using \(target)."
                : "\(label) '\(reference)' was replaced by \(target).")
            return target
        }

        config.theme.dark = mapped(config.theme.dark, "theme.dark")
        config.theme.light = mapped(config.theme.light, "theme.light")
        config.theming.theme = mapped(config.theming.theme, "theming.theme")

        // Cards store 'theme:<id>' or 'wallpaper-file:<path>'; only the
        // theme keys can name a pruned id.
        let prefix = "theme:"
        var keys = favourites.keys
        var moved = 0
        for key in keys where key.hasPrefix(prefix) {
            let id = String(key.dropFirst(prefix.count))
            guard !resolves(id), let target = pruned[id] else { continue }
            keys.remove(key)
            keys.insert(prefix + target)
            moved += 1
        }
        if moved > 0 {
            favourites.save(keys)
            notes.append("Theme favourites: \(moved) pruned id(s) moved to their replacement.")
        }
        return notes
    }

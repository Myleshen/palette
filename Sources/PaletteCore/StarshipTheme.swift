import Foundation
import TOMLKit

/// Builds the Starship config Palette actually points Starship at.
///
/// Starship modules carry literal colour names in their `style` and `format`
/// values, so simply selecting a palette leaves untouched modules on their old
/// terminal colours. This copy resolves those names to the palette's hex values
/// and keeps every other key and module as it was.
///
/// TOMLKit rebuilds the document, so comments in the user's file are dropped.
/// The generated header records that; keys, modules and values are preserved.
public enum StarshipTheme {
    public static let fileName = "starship-theme.toml"
    public static let snippetFileName = "starship-palette.fish"

    /// Used when the user has no `starship.toml`, so the themed prompt is still
    /// visible instead of a bare shell prompt.
    public static let defaultConfig = """
    add_newline = true
    format = "$directory$git_branch$git_status$character"

    [character]
    success_symbol = "[❯](bold green)"
    error_symbol = "[❯](bold red)"
    vimcmd_symbol = "[❮](bold blue)"

    [directory]
    style = "bold blue"
    truncation_length = 3
    truncation_symbol = "…/"

    [git_branch]
    style = "bold purple"

    [git_status]
    style = "bold yellow"
    """

    public struct Result: Sendable, Equatable {
        public var text: String
        /// Something the Apply result should tell the user, or nil.
        public var notice: String?
    }

    /// `userConfig` is the text of `~/.config/starship.toml`; nil/empty writes
    /// the minimal default. `header` is the house "generated by Palette" stamp.
    public static func render(
        userConfig: String?,
        palette: PalettePalette,
        header: String
    ) -> Result {
        let user = userConfig?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        let hadConfig = !user.isEmpty
        var notice: String?
        let table: TOMLTable
        if hadConfig, let parsed = try? TOMLTable(string: user) {
            table = parsed
        } else {
            if hadConfig {
                notice = "~/.config/starship.toml is not valid TOML; the themed copy uses a minimal default."
            } else {
                notice = "No starship.toml found; the themed copy uses a minimal default."
            }
            table = (try? TOMLTable(string: defaultConfig)) ?? TOMLTable()
        }
        remap(table: table, palette: palette)
        let text = [
            header,
            "# colour names replaced with Palette hex values",
            "# comments are dropped by the TOML round-trip",
            "",
            table.convert(),
        ].joined(separator: "\n")
        return Result(text: text, notice: notice)
    }

    /// Fish snippet sourced by the managed block. It exports the themed config
    /// and keeps the fish palette applied.
    public static func fishSnippet(themePath: String, fishPath: String, header: String) -> String {
        [
            header,
            "set -gx STARSHIP_CONFIG \(themePath)",
            "test -f \(fishPath); and source \(fishPath)",
            "",
        ].joined(separator: "\n")
    }

    // MARK: - Remapping

    /// Only style-bearing strings can contain colours. A bare `format` string
    /// has style groups in `(...)`; symbols are format strings too.
    static func isStyleKey(_ key: String) -> Bool {
        let lower = key.lowercased()
        return lower == "style" || lower.hasSuffix("_style")
            || lower == "format" || lower.hasSuffix("_format")
            || lower == "symbol" || lower.hasSuffix("_symbol")
    }

    static func remap(table: TOMLTable, palette: PalettePalette) {
        for key in table.keys {
            guard let value = table[key] else { continue }
            switch value.type {
            case .table:
                if let nested = value.table { remap(table: nested, palette: palette) }
            case .array:
                if let array = value.array {
                    for element in array where element.type == .table {
                        if let nested = element.table { remap(table: nested, palette: palette) }
                    }
                }
            case .string:
                guard isStyleKey(key), let text = value.string else { continue }
                let updated = replacingColours(in: text, palette: palette)
                if updated != text { table[key] = updated }
            default:
                continue
            }
        }
    }

    /// Matches `blue`, `bright-blue`, `fg:blue`, `bg:bright-blue`, but not
    /// `blueish`, `#0000ff` or a hyphenated key. `bold blue` keeps `bold`.
    private static let colourPattern =
        #"(?<![A-Za-z0-9_-])((?:fg:|bg:)?)((?:bright-)?(?:black|red|green|yellow|blue|purple|cyan|white))(?![A-Za-z0-9_-])"#

    static func replacingColours(in text: String, palette: PalettePalette) -> String {
        guard let regex = try? NSRegularExpression(pattern: colourPattern) else { return text }
        let source = text as NSString
        let matches = regex.matches(in: text, range: NSRange(location: 0, length: source.length))
        guard !matches.isEmpty else { return text }
        var output = ""
        var cursor = 0
        for match in matches {
            let name = source.substring(with: match.range(at: 2))
            guard let hex = paletteHex(name, palette: palette) else { continue }
            output += source.substring(with: NSRange(location: cursor, length: match.range.location - cursor))
            output += source.substring(with: match.range(at: 1)) + hex
            cursor = match.range.location + match.range.length
        }
        output += source.substring(from: cursor)
        return output
    }

    /// ANSI 0...7 for the base names, 8...15 for `bright-*`.
    static func paletteHex(_ name: String, palette: PalettePalette) -> String? {
        let names = ["black", "red", "green", "yellow", "blue", "purple", "cyan", "white"]
        var base = name
        var bright = false
        if base.hasPrefix("bright-") {
            bright = true
            base.removeFirst("bright-".count)
        }
        guard let index = names.firstIndex(of: base) else { return nil }
        let slot = (bright ? 8 : 0) + index
        guard palette.ansi.indices.contains(slot) else { return nil }
        return palette.ansi[slot]
    }
}
